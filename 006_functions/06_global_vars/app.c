#include <stdio.h>

// Глобальные переменные объявлены ВНЕ функций.
// Они видны всем функциям в файле и живут всё время работы программы.
// Здесь это общее состояние игры: счёт и число жизней.
int score = 0;
int lives = 3;

// Функция меняет глобальную переменную — параметр ей для этого не нужен.
void add_points(int points)
{
    score += points; // работаем с общим score
    printf("+%d очков (счёт: %d)\n", points, score);
}

// Другая функция читает и меняет ТУ ЖЕ переменную lives.
void lose_life()
{
    lives--; // тот же самый lives, что видит и main
    printf("Потеряна жизнь (осталось: %d)\n", lives);
}

// Функция только читает глобальные переменные.
void show_status()
{
    printf("--- Статус: счёт=%d, жизней=%d ---\n", score, lives);
}

int main()
{
    show_status();      // счёт=0, жизней=3

    add_points(10);
    add_points(25);     // score накапливается между вызовами
    lose_life();

    show_status();      // видим изменения, сделанные другими функциями

    return 0;
}
