#include <stdio.h>

// static-переменная внутри функции создаётся ОДИН раз и сохраняет
// своё значение между вызовами (в отличие от обычной локальной,
// которая создаётся заново при каждом входе в функцию).

void counter()
{
    int normal = 0;         // создаётся заново каждый вызов -> всегда 0
    static int calls = 0;   // живёт всё время программы, помнит значение

    normal++;
    calls++;

    printf("normal=%d, static calls=%d\n", normal, calls);
}

// Практический пример: генератор уникальных ID.
// Каждому новому объекту нужен свой номер — static хранит "следующий".
int next_id()
{
    static int id = 1000; // инициализируется один раз при первом вызове
    return id++;           // вернуть текущий и увеличить для следующего
}

int main()
{
    // normal каждый раз 0, а calls накапливается: 1, 2, 3.
    counter();
    counter();
    counter();

    printf("---\n");

    // Каждый вызов даёт новый уникальный номер.
    printf("Новый пользователь: id=%d\n", next_id());
    printf("Новый пользователь: id=%d\n", next_id());
    printf("Новый пользователь: id=%d\n", next_id());

    return 0;
}
