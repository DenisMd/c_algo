// Большой ИНИЦИАЛИЗИРОВАННЫЙ глобальный массив -> секция .data.
// Раз есть ненулевые значения, все байты придётся хранить в файле,
// поэтому бинарник заметно растолстеет (~1 МБ). Сравни с big_bss.c.

#define N (256 * 1024) // 256K int = 1 МБ данных

int big[N] = { 1 }; // хотя бы один ненулевой элемент -> точно .data, не .bss

int main(void) {
  return big[0]; // используем, чтобы линкер не выкинул
}
