#include <stdio.h>

// Глобальные массивы и то, где они физически хранятся.
//
// Инициализированный глобальный массив компилятор кладёт прямо в бинарник,
// в секцию .data — то есть его байты РЕАЛЬНО лежат в файле программы.
// Ниже проверяем это через readelf/objdump/nm/size. См. README.md.

// .data — есть начальные значения -> байты записаны в файл.
// Значения подобраны так, чтобы их было легко узнать в hex-дампе секции.
int global_data[] = { 0x11223344, 0x55667788, 0x77665544, 0x33221100 };

// .rodata — только для чтения (const) -> тоже лежит в файле, но в другой секции.
const int global_ro[] = { 0x0BADF00D, 0x0C0FFEE0, 0x12345678 };

// .bss — нет инициализатора (нули) -> в файле НЕ хранится, только резервируется
// размер; ОС обнулит эту память при запуске. 256 int = 1024 байта "из воздуха".
int global_bss[256];

int main()
{
  // локальный массив живёт на стеке — его в файле нет вообще.
  int local[4] = { 1, 2, 3, 4 };

  printf("global_data @ %p  = { 0x%08X, ... }  -> секция .data\n",
         (void*)global_data, (unsigned)global_data[0]);
  printf("global_ro   @ %p  = { 0x%08X, ... }  -> секция .rodata\n",
         (void*)global_ro, (unsigned)global_ro[0]);
  printf("global_bss  @ %p  = { %d, ... }        -> секция .bss (нули)\n",
         (void*)global_bss, global_bss[0]);
  printf("local       @ %p  = { %d, ... }        -> стек (в файле нет)\n",
         (void*)local, local[0]);

  return 0;
}
