#include <stdio.h>

// Точка 1: выходом за границу можно ЗАКОРРАПТИТЬ (испортить) чужую память.
//
// Объявим два массива подряд. В памяти локальные переменные лежат рядом,
// поэтому запись ЗА концом первого массива попадает во второй — хотя во
// второй мы напрямую ничего не писали. Никакой ошибки не будет: просто
// у victim молча меняются значения.
//
// Точная раскладка зависит от компилятора (это часть природы UB). На нашем
// gcc без оптимизаций arr и victim лежат вплотную, и arr[ARR_SIZE] совпадает
// с victim[0]. Именно так тихие баги портят соседние данные.

#define ARR_SIZE 8

int main()
{
  int arr[ARR_SIZE];
  int victim[ARR_SIZE];

  for(size_t i=0; i < ARR_SIZE; i++) {
    arr[i]    = (int)i;
    victim[i] = 100 + (int)i;
  }

  printf("до порчи:    victim[0] = %d, victim[1] = %d\n", victim[0], victim[1]);

  // пишем ЗА границей arr -> попадаем в соседний victim
  arr[ARR_SIZE]     = 4242; // UB: индекс ARR_SIZE уже вне arr -> victim[0]
  arr[ARR_SIZE + 1] = 9999; // -> victim[1]

  printf("после порчи: victim[0] = %d, victim[1] = %d"
         "  <- перезаписали, не трогая victim напрямую!\n",
         victim[0], victim[1]);

  if(victim[0] != 100 || victim[1] != 101) {
    printf("память закоррапчена: соседний массив испорчен записью в arr\n");
  }

  // прочитаем arr, чтобы он был "использован" (иначе -Wall ругается)
  printf("arr[0] = %d, arr[%d-1] = %d\n", arr[0], ARR_SIZE, arr[ARR_SIZE - 1]);

  return 0;
}
