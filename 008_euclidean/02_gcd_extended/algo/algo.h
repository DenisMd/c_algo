#ifndef ALGO_H
#define ALGO_H

// ---- Расширенный алгоритм Евклида ----
//
// Обычный алгоритм находит g = gcd(a, b). Расширенный вдобавок находит
// коэффициенты x и y такие, что выполняется соотношение Безу:
//
//     a * x + b * y = g
//
// Например, gcd(12, 8) = 4, и 12*1 + 8*(-1) = 4  =>  x = 1, y = -1.
//
// Идея: тот же цикл делений, что и в обычном алгоритме, но параллельно с
// остатками мы ведём коэффициенты при a и при b, обновляя их той же формулой.
//
// Возвращаемое значение — сам НОД g (всегда неотрицательный).
// Коэффициенты x и y функция записывает по переданным указателям.

// Итеративная версия (цикл while).
long long gcd_ext(long long a, long long b, long long *x, long long *y);

// Рекурсивная версия — та же формула, записанная буквально.
long long gcd_ext_rec(long long a, long long b, long long *x, long long *y);

#endif
