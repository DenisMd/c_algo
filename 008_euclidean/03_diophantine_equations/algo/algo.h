#ifndef DIOPHANTINE_H
#define DIOPHANTINE_H

// ---- Линейное диофантово уравнение с двумя неизвестными ----
//
// Уравнение:  a*x + b*y = c   (a, b, c — заданы; x, y — целые неизвестные).
//
// Целые решения существуют тогда и только тогда, когда gcd(a, b) делит c.
// Одно частное решение получаем из расширенного алгоритма Евклида
// (см. соседний урок 02_gcd_extended): он даёт x0, y0 с a*x0 + b*y0 = g,
// после чего домножаем их на c/g.
//
// Возвращает 1, если решение найдено (и пишет x, y по указателям), иначе 0.
int solve_diophantine(long long a, long long b, long long c, long long *x,
                      long long *y);

#endif
